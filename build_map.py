"""Build map-data.js for the Areas map tab.

Inputs (all committed):
  data/locations.json   – the location study (scores + facts per municipality)
  data/boundaries.json  – municipality polygons for the 5 prefectures (国土数値情報 N03, 1% simplified)
  data/map_extras.json  – Costco warehouses, Tokyo Station, commuter-bus origins
  areas.json            – areas the daily SUUMO scrape tracks (to link map → listings)
  optional (track B):   data/commute_matrix.json (office picker), data/area_health.json (paediatrics),
                        data/area_noise.json (aircraft noise) — info only, not part of the score

Run:  python build_map.py                 (rebuild map-data.js)
      python build_map.py --fetch-boundaries   (one-off: refresh data/boundaries.json)
"""
import json, os, sys, urllib.request

PREFS = ["08", "11", "12", "13", "14"]          # Ibaraki, Saitama, Chiba, Tokyo, Kanagawa
BBOX = (139.0, 35.15, 140.65, 36.3)             # lon/lat window drawn on the map (drops Tokyo islands etc.)
SRC = ("https://raw.githubusercontent.com/smartnews-smri/japan-topography/main/"
       "data/municipality/geojson/s0010/N03-21_{}_210101.json")


def rnd(c):
    return [round(c[0], 4), round(c[1], 4)]


def fetch_boundaries():
    feats = []
    for p in PREFS:
        with urllib.request.urlopen(SRC.format(p)) as r:
            fc = json.load(r)
        for f in fc["features"]:
            pr, g = f["properties"], f["geometry"]
            polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
            polys = [[[rnd(c) for c in ring] for ring in poly] for poly in polys]
            pts = [c for poly in polys for c in poly[0]]
            lon = sum(c[0] for c in pts) / len(pts); lat = sum(c[1] for c in pts) / len(pts)
            if not (BBOX[0] <= lon <= BBOX[2] and BBOX[1] <= lat <= BBOX[3]):
                continue
            feats.append({"code": pr["N03_007"], "pref": pr["N03_001"],
                          "name": (pr.get("N03_003") or "") + (pr.get("N03_004") or ""),
                          "poly": polys})
    json.dump({"source": "国土数値情報（行政区域データ）N03, 2021-01-01, via smartnews-smri/japan-topography (1% simplified)",
               "features": feats}, open("data/boundaries.json", "w", encoding="utf-8"),
              ensure_ascii=False, separators=(",", ":"))
    print(f"boundaries: {len(feats)} municipalities")


def build():
    loc = json.load(open("data/locations.json", encoding="utf-8"))
    bnd = json.load(open("data/boundaries.json", encoding="utf-8"))
    extras = json.load(open("data/map_extras.json", encoding="utf-8"))
    tracked = {str(a["sc"]): a.get("group", a["key"]) for a in json.load(open("areas.json", encoding="utf-8"))}

    by_name = {}
    for f in bnd["features"]:
        by_name.setdefault(f["name"], []).append(f)

    # info-only layers (track B, manual refresh) — shown as pros/cons/info and in Compare, never scored
    info = {key: json.load(open(f, encoding="utf-8")) for key, f in
            (("health", "data/area_health.json"), ("noise", "data/area_noise.json")) if os.path.exists(f)}

    areas, used = [], set()
    for a in loc["areas"]:
        fs = by_name.get(a["nameJa"])
        if not fs:
            raise SystemExit(f"no boundary for {a['id']} {a['nameJa']}")
        f = fs[0]
        used.add(f["code"])
        a = dict(a, code=f["code"], poly=f["poly"], tracked=tracked.get(f["code"]))
        for key, data in info.items():                       # info-only extras (not scored)
            if a["id"] in data["areas"]:
                a[key] = data["areas"][a["id"]]
        areas.append(a)

    context = [{"code": f["code"], "name": f["name"], "poly": f["poly"]}
               for f in bnd["features"] if f["code"] not in used]

    out = {"generated": loc["generated"], "hazardGenerated": loc.get("hazardGenerated"), "weights": loc["weights"], "shortlistSize": loc.get("shortlistSize"), "spaceGate": loc.get("spaceGate"),
           "referenceFamily": loc.get("referenceFamily"), "areas": areas, "context": context,
           "costco": extras["costco"], "tokyoStation": extras["tokyoStation"], "busOrigins": extras["busOrigins"],
           "boundarySource": bnd["source"],
           "info": {k: {"generated": v["generated"], "source": v["source"]} for k, v in info.items()}}
    if os.path.exists("data/commute_matrix.json"):          # office picker (commute_matrix.py, track B)
        cm = json.load(open("data/commute_matrix.json", encoding="utf-8"))
        out["commute"] = {k: cm[k] for k in ("generated", "searchDate", "offices", "matrix")}
    js ="/* generated by build_map.py — do not edit */\nconst MAP_DATA = " + \
         json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
    open("map-data.js", "w", encoding="utf-8").write(js)
    print(f"map-data.js: {len(areas)} areas, {len(context)} context polygons, {len(js)//1024} KB")


if __name__ == "__main__":
    if "--fetch-boundaries" in sys.argv:
        fetch_boundaries()
    build()
